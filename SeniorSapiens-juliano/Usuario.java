public class Usuario {

    private String nome;
    private int idade;
    private int ID;

    //==========================================================

    public String getNome(){

        return nome;

    }

    public int getIdade(){

        return idade;

    }

    public int getID(){

        return ID;

    }

    //==========================================================

    public void setNome(String nome){

        this.nome = nome;

    }

    public void setIdade(int idade){

        this.idade = idade;
        
    }

    public void setID(int ID){

        this.ID = ID;

    }
    
}
